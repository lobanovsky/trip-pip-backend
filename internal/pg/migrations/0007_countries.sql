-- Справочник стран: общий список кодов и названий (countries) плюс
-- надстройка на агентство (agency_countries) для видимости/порядка.
-- Отдельная таблица для видимости, а не колонки is_active/sort_order прямо
-- на countries, — чтобы PATCH одного агентства не мог поменять то, что
-- видят остальные: countries тут единственная глобальная таблица без
-- agency_id, и держать в ней изменяемые агентством поля было бы утечкой
-- между тенантами.

CREATE TABLE countries (
    code text PRIMARY KEY CHECK (code ~ '^[A-Z]{2}$'),
    name text NOT NULL CHECK (length(btrim(name)) > 0)
);

CREATE TABLE agency_countries (
    agency_id    uuid        NOT NULL REFERENCES agencies (id) ON DELETE CASCADE,
    country_code text        NOT NULL REFERENCES countries (code),
    is_active    boolean     NOT NULL DEFAULT true,
    sort_order   integer     NOT NULL DEFAULT 0,
    created_at   timestamptz NOT NULL DEFAULT now(),
    updated_at   timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (agency_id, country_code)
);

CREATE TRIGGER agency_countries_updated_at BEFORE UPDATE ON agency_countries
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

